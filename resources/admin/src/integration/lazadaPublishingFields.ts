import type {PublishingSource} from './marketplacePublishing';
import {orderedPublishingVariants} from './marketplaceVariantOrdering';

export interface LazadaPublishingField {
 key:string; name:string; label:string; sku?:string; type:string; options:string[];
 required:boolean; value:string; complete:boolean; supported:boolean; automatic:boolean; sizeChart:boolean;
}
const supported=['text','richtext','numeric','date','singleselect','multiselect','enuminput','multienuminput','img'];
function valid(type:string,value:string,options:string[]):boolean {
 if(!value.trim())return false;
 if(type==='numeric')return Number.isFinite(Number(value));
 if(type==='date'){
  if(!/^\d{4}-\d{2}-\d{2}$/.test(value))return false;
  const date=new Date(`${value}T00:00:00Z`);
  return !Number.isNaN(date.valueOf())&&date.toISOString().slice(0,10)===value;
 }
 if(type==='img')return false;
 if(type==='singleselect')return options.includes(value);
 if(type==='multiselect')return value.split(',').every(v=>options.includes(v.trim()));
 return supported.includes(type);
}

export function lazadaPublishingFields(schema:unknown,source:PublishingSource,edits:Record<string,string>,brands:string[]=[]):LazadaPublishingField[] {
 if(!Array.isArray(schema))throw new Error('Category attributes could not be read.');
 const seen=new Set<string>();const fields:LazadaPublishingField[]=[];
 for(const attribute of schema){
  if(!attribute||typeof attribute.name!=='string'||!/^[_a-zA-Z][_a-zA-Z0-9]*$/.test(attribute.name)
   ||['__proto__','constructor','prototype'].includes(attribute.name)
   ||!['normal','sku'].includes(attribute.attribute_type)||typeof attribute.input_type!=='string'
   ||![0,1,false,true].includes(attribute.is_mandatory))throw new Error('Category attributes could not be read.');
  const name=attribute.name;const scope=attribute.attribute_type;const type=attribute.input_type.toLowerCase();
  const sizeChart=scope==='normal'&&(/size[_ ]?chart/i.test(name)||/size chart/i.test(String(attribute.label??'')));
  const identity=`${scope}:${name}`;if(seen.has(identity))throw new Error('Duplicate category attribute.');seen.add(identity);
  // Image URLs are generated by the backend; never ask staff to supply platform URLs.
  if(name==='__images__')continue;
  const options=Array.isArray(attribute.options)?attribute.options.flatMap((o:unknown)=>o&&typeof o==='object'&&'en_name' in o&&typeof o.en_name==='string'?[o.en_name]:[]):[];
  if(name==='brand'&&scope==='normal'&&type==='singleselect'&&!options.length) options.push(...new Set(['No Brand',...brands]));
  const targets=scope==='sku'?orderedPublishingVariants(source.options,source.variants):[undefined];
  for(const variant of targets){
   const key=variant?`sku:${variant.sku}:${name}`:`normal:${name}`;
   const own:Record<string,unknown>=variant?{SellerSku:variant.sku,price:(variant.price_minor/100).toFixed(2),quantity:'0',
    package_weight:variant.weight_grams?variant.weight_grams/1000:null,package_length:variant.package_length_cm,
    package_width:variant.package_width_cm,package_height:variant.package_height_cm}
    :{name:source.title,description:source.description,brand:source.brand};
   const saved=own[name];const automatic=typeof saved==='string'||typeof saved==='number';
   const value=Object.hasOwn(edits,key)?edits[key]:automatic?String(saved):'';
   fields.push({key,name,sku:variant?.sku,label:typeof attribute.label==='string'?attribute.label:name,type,options,sizeChart,
    required:!!attribute.is_mandatory || !!variant&&source.variants.length>1&&attribute.is_sale_prop==1,
    value,automatic,supported:supported.includes(type),complete:valid(type,value,options)});
  }
 }
 return fields;
}

export function lazadaPublishingValues(fields:LazadaPublishingField[]):{normal:Record<string,string>;skus:Record<string,Record<string,string>>} {
 const normal:Record<string,string>=Object.create(null);const skus:Record<string,Record<string,string>>=Object.create(null);
 for(const field of fields){
  if(field.sizeChart)continue;
  if(!field.value.trim())continue;
  const target=field.sku?(skus[field.sku]??=Object.create(null)):normal;
  target[field.name]=field.value;
 }
 return {normal,skus};
}
