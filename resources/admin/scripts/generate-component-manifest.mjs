import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assertInventoryCompleteness, collectComponentPaths } from './componentInventory.mjs';

const adminRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const componentsRoot = resolve(adminRoot, 'src/components');
const manifestPath = resolve(adminRoot, '../../docs/admin-react/component-manifest.md');
const requiredContractPath = resolve(adminRoot, 'component-inventory.required.json');
const requiredComponents = JSON.parse(readFileSync(requiredContractPath, 'utf8')).requiredComponentPaths;
const components = assertInventoryCompleteness(
  collectComponentPaths(componentsRoot, adminRoot),
  requiredComponents,
);
const document = [
  '# Admin React component manifest',
  '',
  `Generated from the current Admin source on ${components.length} component files.`,
  'The required-path contract is independently maintained in `component-inventory.required.json` and is not regenerated by this command.',
  '',
  'Regenerate deterministically from `resources/admin`:',
  '',
  '```powershell',
  'npm run inventory:components',
  '```',
  '',
  '| Component path |',
  '| --- |',
  ...components.map((component) => `| \`${component}\` |`),
  '',
].join('\n');

writeFileSync(manifestPath, document, 'utf8');
